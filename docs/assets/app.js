/* Bench Press dashboard. Data: window.BP_ITEMS (appendix tables and figures), window.BP_EXPLORER (counts per cell,
   model and configuration), window.BP_CODEBOOK. Data strings go into the DOM with textContent; captions and notes are
   HTML generated by export_dashboard.py from the project's own caption files. */
(function () {
  "use strict";
  const IT = window.BP_ITEMS, EX = window.BP_EXPLORER, CB = window.BP_CODEBOOK;
  const css = getComputedStyle(document.documentElement);
  const tok = (n) => css.getPropertyValue(n).trim();
  const COLORS = ["--m1", "--m2", "--m3", "--m4"].map(tok);
  const INK = tok("--ink"), INK2 = tok("--ink-2"), MUTED = tok("--muted"), GRID = tok("--grid"), AXIS = tok("--axis"),
    SURFACE = tok("--surface");
  // diverging scale around chance (50%) for accuracy heat cells: red arm below, blue arm above, gray midpoint
  const BLUE = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#104281"];
  const RED = ["#f6d5d3", "#eeaeaa", "#e3837e", "#d55752", "#b8332f", "#8c1f1c"];
  const MID = "#f0efec";
  const CONFIGS = [["C0", [0]], ["C1", [1]], ["C2", [2]], ["C3", [3]], ["C4", [4]],
    ["C0–C1 (without the code)", [0, 1]], ["C2–C4 (with the code)", [2, 3, 4]]];
  const M = EX.models.length;
  const $ = (id) => document.getElementById(id);
  const el = (tag, attrs = {}, text) => {
    const e = document.createElement(tag);
    for (const [k, v] of Object.entries(attrs)) {
      if (k === "class") e.className = v; else if (k === "html") e.innerHTML = v; else e.setAttribute(k, v);
    }
    if (text !== undefined) e.textContent = text;
    return e;
  };
  const pct = (x, d = 1) => (x == null || isNaN(x) ? "–" : (100 * x).toFixed(d) + "%");

  // ------------------------------------------------------------ explorer data
  const SRC = new Map(EX.sources.map(([id, name, type, region]) => [id, { id, name, type, region }]));
  const CELLS = EX.cells.map((r) => ({ cell: r[0], src: r[1], tid: r[2], tension: r[3], shared: r[4], group: r[5],
    side: r[6], other: r[7], c: r[8] }));
  const BY_SRC = new Map();
  CELLS.forEach((c) => { if (!BY_SRC.has(c.src)) BY_SRC.set(c.src, []); BY_SRC.get(c.src).push(c); });
  function agg(cells, m, cfgs) {
    let k = 0, n = 0;
    for (const c of cells) for (const f of cfgs) { const i = 2 * (m * 5 + f); k += c.c[i]; n += c.c[i + 1]; }
    return { k, n, acc: n ? k / n : null };
  }

  // ------------------------------------------------------------ plotly helpers
  const BASE = {
    font: { family: "system-ui, -apple-system, Segoe UI, sans-serif", size: 12, color: INK2 },
    paper_bgcolor: SURFACE, plot_bgcolor: SURFACE, margin: { l: 56, r: 120, t: 10, b: 44 },
    hoverlabel: { bgcolor: SURFACE, bordercolor: AXIS, font: { color: INK } },
    xaxis: { gridcolor: GRID, linecolor: AXIS, zeroline: false, tickfont: { color: MUTED } },
    yaxis: { gridcolor: GRID, linecolor: AXIS, zeroline: false, tickfont: { color: MUTED }, ticksuffix: "%" },
    legend: { orientation: "h", y: -0.18, font: { color: INK2 } },
  };
  const PCONF = { displaylogo: false, responsive: true, modeBarButtonsToRemove: ["select2d", "lasso2d", "autoScale2d"] };
  const layout = (extra) => Object.assign({}, BASE, extra, {
    xaxis: Object.assign({}, BASE.xaxis, extra.xaxis || {}), yaxis: Object.assign({}, BASE.yaxis, extra.yaxis || {}) });
  function endLabels(xs, series, span, top) { // direct labels at the line ends, nudged apart so they never collide
    const gap = span * 0.07;              // about one label height at the charts' plot height
    const pts = series.map((s, i) => ({ i, y: s[s.length - 1] })).filter((p) => p.y != null).sort((a, b) => a.y - b.y);
    for (let j = 1; j < pts.length; j++) if (pts[j].y - pts[j - 1].y < gap) pts[j].y = pts[j - 1].y + gap;
    if (pts.length && pts[pts.length - 1].y > top) {   // pushed past the top of the plot: stack down from the top
      pts[pts.length - 1].y = top;
      for (let j = pts.length - 2; j >= 0; j--) pts[j].y = Math.min(pts[j].y, pts[j + 1].y - gap);
    }
    return pts.map((p) => ({ x: xs[xs.length - 1], y: p.y, xanchor: "left", xshift: 10, showarrow: false,
      text: EX.models[p.i], font: { color: INK, size: 12 } }));
  }

  // ------------------------------------------------------------ overview
  function overview() {
    const tiles = $("tiles");
    if (!tiles.childElementCount) {
      const nAns = CELLS.reduce((s, c) => s + c.c.filter((_, i) => i % 2 === 1).reduce((a, b) => a + b, 0), 0);
      [[SRC.size, "codes of ethics"], [CELLS.length, "code × tension cells"], [M, "open-weight models"],
        [5, "prompting configurations"], [nAns.toLocaleString("en"), "answers shown (no-rationale arm)"]]
        .forEach(([v, k]) => { const t = el("div", { class: "tile" }); t.append(el("div", { class: "v" }, String(v)),
          el("div", { class: "k" }, k)); tiles.append(t); });
    }
    const xs = ["C0", "C1", "C2", "C3", "C4"];
    const ys = EX.models.map((_, m) => xs.map((_, f) => 100 * agg(CELLS, m, [f]).acc));
    Plotly.react("ov-ladder", ys.map((y, m) => ({ x: xs, y, name: EX.models[m], type: "scatter", mode: "lines+markers",
      line: { color: COLORS[m], width: 2 }, marker: { size: 8, color: COLORS[m], line: { color: SURFACE, width: 2 } },
      hovertemplate: "%{y:.1f}%<extra>" + EX.models[m] + "</extra>" })),
    layout({ hovermode: "x unified", yaxis: { range: [50, 100], title: { text: "Accuracy", font: { color: INK2 } } },
      annotations: endLabels(xs, ys, 50, 99), shapes: [] }), PCONF);

    const cfg = CONFIGS[+$("ov-config").value][1];
    const traces = EX.models.map((name, m) => {
      const pts = [...BY_SRC.entries()].map(([sid, cells]) => ({ sid, a: agg(cells, m, cfg) })).filter((p) => p.a.n);
      return { type: "scatter", mode: "markers", name, x: pts.map((p) => 100 * p.a.acc),
        y: pts.map((p, i) => m + ((i * 0.6180339) % 1 - 0.5) * 0.5),
        customdata: pts.map((p) => [SRC.get(p.sid).name, p.a.n, p.sid]),
        marker: { size: 8, color: COLORS[m], opacity: 0.85, line: { color: SURFACE, width: 1 } },
        hovertemplate: "<b>%{x:.1f}%</b> %{customdata[0]}<br>%{customdata[1]} answers<extra>" + name + "</extra>" };
    });
    Plotly.react("ov-codes", traces, layout({ hovermode: "closest", showlegend: true, margin: { l: 130, r: 20, t: 10, b: 90 },
      legend: Object.assign({}, BASE.legend, { y: -0.32 }),
      xaxis: { range: [0, 101], ticksuffix: "%", title: { text: "Accuracy on the code", font: { color: INK2 } } },
      yaxis: { tickmode: "array", tickvals: [0, 1, 2, 3], ticktext: EX.models, ticksuffix: "", range: [3.6, -0.6],
        tickfont: { color: INK } },
      shapes: [{ type: "line", x0: 50, x1: 50, y0: -0.6, y1: 3.6, line: { color: AXIS, dash: "dot", width: 1 } }] }), PCONF);
    const plot = $("ov-codes");
    plot.removeAllListeners && plot.removeAllListeners("plotly_click");
    plot.on("plotly_click", (ev) => { location.hash = "#explorer/" + ev.points[0].customdata[2]; });
  }

  // ------------------------------------------------------------ explorer
  let exSrc = null;
  function fillCodeSelect() {          // all codes, grouped by region; the search box narrows the list
    const sel = $("ex-code"), q = $("ex-search").value.trim().toLowerCase();
    const match = (s) => !q || [s.name, s.region, s.type].some((v) => String(v).toLowerCase().includes(q));
    const regions = new Map();
    [...SRC.values()].filter(match).sort((a, b) => a.name.localeCompare(b.name)).forEach((s) => {
      if (!regions.has(s.region)) regions.set(s.region, []);
      regions.get(s.region).push(s);
    });
    sel.replaceChildren();
    let n = 0;
    [...regions.keys()].sort().forEach((r) => {
      const g = el("optgroup", { label: r });
      regions.get(r).forEach((s) => { g.append(el("option", { value: s.id }, `${s.name} (${(BY_SRC.get(s.id) || []).length})`)); n++; });
      sel.append(g);
    });
    if (!n) sel.append(el("option", { value: "", disabled: "" }, "No code matches the search"));
    $("ex-count").textContent = q ? `· ${n} of ${SRC.size} match` : `· ${SRC.size} codes by region (number of tensions)`;
    if (exSrc && [...sel.options].some((o) => o.value === exSrc)) sel.value = exSrc;
    else if (n && q) location.hash = "#explorer/" + sel.options[0].value;   // narrowed past the current code
  }
  function explorerInit() {
    fillCodeSelect();
    $("ex-search").addEventListener("input", fillCodeSelect);
    $("ex-code").addEventListener("change", () => { location.hash = "#explorer/" + $("ex-code").value; });
    $("ex-config").addEventListener("change", () => exSrc && explorer(exSrc));
    $("ex-csv").addEventListener("click", () => exSrc && downloadCsv(exSrc + ".csv", exTable.columns, exTable.rows));
  }
  let exTable = { columns: [], rows: [] };
  function explorer(sid) {
    if (!SRC.has(sid)) sid = [...SRC.keys()].sort()[0];
    exSrc = sid;
    const s = SRC.get(sid), cells = BY_SRC.get(sid) || [];
    if (![...$("ex-code").options].some((o) => o.value === sid)) { $("ex-search").value = ""; fillCodeSelect(); }
    $("ex-code").value = sid;
    $("ex-title").textContent = "Accuracy on " + s.name;
    $("ex-meta").textContent = `${s.type} · ${s.region} · ${cells.length} value tension${cells.length === 1 ? "" : "s"}`;
    const xs = ["C0", "C1", "C2", "C3", "C4"];
    const ys = EX.models.map((_, m) => xs.map((_, f) => { const a = agg(cells, m, [f]); return a.n ? 100 * a.acc : null; }));
    const all = EX.models.map((_, m) => xs.map((_, f) => 100 * agg(CELLS, m, [f]).acc));
    const traces = [];
    EX.models.forEach((name, m) => {
      traces.push({ x: xs, y: all[m], name: name + " (all codes)", showlegend: false, type: "scatter", mode: "lines",
        line: { color: COLORS[m], width: 1.5, dash: "dot" }, opacity: 0.7, hoverinfo: "skip" });
    });
    EX.models.forEach((name, m) => {
      traces.push({ x: xs, y: ys[m], name, type: "scatter", mode: "lines+markers", line: { color: COLORS[m], width: 2 },
        marker: { size: 8, color: COLORS[m], line: { color: SURFACE, width: 2 } },
        customdata: xs.map((_, f) => [agg(cells, m, [f]).n, all[m][f]]),
        hovertemplate: "%{y:.1f}% <span style='color:" + MUTED + "'>(all codes %{customdata[1]:.1f}%, %{customdata[0]} answers)</span><extra>" + name + "</extra>" });
    });
    Plotly.react("ex-ladder", traces, layout({ hovermode: "x unified", yaxis: { range: [0, 101] },
      annotations: endLabels(xs, ys, 100, 99) }), PCONF);

    const ci = +$("ex-config").value, cfg = CONFIGS[ci][1];
    const rank = $("ex-rank");
    rank.replaceChildren();
    EX.models.forEach((name, m) => {
      const vals = [...BY_SRC.entries()].map(([id, cs]) => ({ id, a: agg(cs, m, cfg).acc })).filter((v) => v.a != null)
        .sort((a, b) => b.a - a.a);
      const pos = vals.findIndex((v) => v.id === sid);
      const row = el("div", { class: "rank-row" });
      const lab = el("div"); lab.append(el("span", { class: "key", style: `background:${COLORS[m]}` }), document.createTextNode(name));
      const track = el("div", { class: "rank-track", title: `${name}: rank ${pos + 1} of ${vals.length}` });
      if (pos >= 0) track.append(el("span", { class: "rank-dot",
        style: `left:${vals.length > 1 ? 100 - (100 * pos) / (vals.length - 1) : 50}%;background:${COLORS[m]}` }));
      row.append(lab, track, el("div", { class: "num" }, pos >= 0 ? `${pos + 1} of ${vals.length}` : "–"));
      rank.append(row);
    });
    rank.append(el("p", { class: "hint" }, `At ${CONFIGS[ci][0]}; right = highest accuracy among the codes.`));

    // accuracy columns right after the tension, so they stay in view; the long texts follow
    const cols = ["Tension", ...EX.models.map((n) => n + " %"), "Answers per model", "The code's side",
      "The other side", "Shared tension", "Value group"];
    const rows = cells.map((c) => {
      const accs = EX.models.map((_, m) => agg([c], m, cfg));
      return [`${c.tid}: ${c.tension}`, ...accs.map((a) => (a.n ? (100 * a.acc).toFixed(1) : "")), String(accs[0].n),
        c.side, c.other, c.shared, c.group];
    }).sort((a, b) => mean(a.slice(1, 1 + M)) - mean(b.slice(1, 1 + M)));
    exTable = { columns: cols, rows };
    renderTable($("ex-table"), cols, rows, { heat: new Set(EX.models.map((_, m) => 1 + m)), filter: false,
      wrap: new Set([0, M + 2, M + 3]) });
  }
  const mean = (xs) => { const v = xs.filter((x) => x !== "").map(Number); return v.length ? v.reduce((a, b) => a + b, 0) / v.length : 999; };

  // ------------------------------------------------------------ generic table
  const num = (v) => { const m = String(v).replace("−", "-").match(/^\s*([-+]?\d+(?:\.\d+)?)/); return m ? parseFloat(m[1]) : null; };
  function heatStyle(v) {
    const x = num(v);
    if (x == null) return "";
    const d = (x - 50) / 50;                       // -1 (always wrong) .. 0 (chance) .. +1 (always right)
    if (Math.abs(d) < 0.1) return `background:${MID};color:${INK}`;
    const arm = d > 0 ? BLUE : RED;
    const i = Math.min(arm.length - 1, Math.floor(((Math.abs(d) - 0.1) / 0.9) * arm.length));
    return `background:${arm[i]};color:${i >= 3 ? "#fff" : INK}`;
  }
  function renderTable(box, columns, rows, opts = {}) {
    box.replaceChildren();
    let shown = rows.slice(), sortCol = -1, dir = 1;
    const numeric = columns.map((_, j) => rows.length && rows.filter((r) => r[j] !== "" && r[j] != null)
      .every((r) => num(r[j]) != null));
    const table = el("table"), thead = el("thead"), tbody = el("tbody"), hr = el("tr");
    columns.forEach((c, j) => {
      const th = el("th", { scope: "col", tabindex: "0" }, c);
      const go = () => { dir = sortCol === j ? -dir : 1; sortCol = j; draw(); };
      th.addEventListener("click", go);
      th.addEventListener("keydown", (e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); go(); } });
      hr.append(th);
    });
    thead.append(hr); table.append(thead, tbody);
    function draw() {
      let r = shown.slice();
      if (sortCol >= 0) r.sort((a, b) => {
        const x = a[sortCol], y = b[sortCol];
        if (numeric[sortCol]) return dir * ((num(x) ?? -1e9) - (num(y) ?? -1e9));
        return dir * String(x).localeCompare(String(y));
      });
      [...hr.children].forEach((th, j) => th.setAttribute("aria-sort", j === sortCol ? (dir > 0 ? "ascending" : "descending") : "none"));
      tbody.replaceChildren(...r.map((row) => {
        const tr = el("tr");
        row.forEach((v, j) => {
          const td = el("td", {}, v == null ? "" : String(v));
          if (opts.heat && opts.heat.has(j)) { td.className = "heat"; td.setAttribute("style", heatStyle(v)); }
          else if (numeric[j]) td.className = "num";
          if (opts.wrap && opts.wrap.has(j)) td.style.minWidth = "260px";
          tr.append(td);
        });
        return tr;
      }));
    }
    if (opts.filter !== false) {
      const tools = el("div", { class: "table-tools" });
      const f = el("input", { type: "search", placeholder: "Filter rows", "aria-label": "Filter rows" });
      const count = el("span", { class: "hint" });
      f.addEventListener("input", () => {
        const q = f.value.toLowerCase();
        shown = rows.filter((r) => r.some((v) => String(v).toLowerCase().includes(q)));
        count.textContent = `${shown.length} of ${rows.length} rows`;
        draw();
      });
      count.textContent = `${rows.length} rows`;
      tools.append(f, count);
      if (opts.csv) tools.append(el("a", { class: "btn", href: opts.csv, download: "" }, "Download CSV"));
      box.append(tools);
    }
    const wrap = el("div", { class: "table-wrap" });
    wrap.append(table); box.append(wrap);
    draw();
  }
  function downloadCsv(name, cols, rows) {
    const q = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;
    const blob = new Blob(["﻿" + [cols, ...rows].map((r) => r.map(q).join(",")).join("\n")], { type: "text/csv" });
    const a = el("a", { href: URL.createObjectURL(blob), download: name });
    document.body.append(a); a.click(); a.remove();
  }

  // ------------------------------------------------------------ tables & figures
  const ITEMS = IT.items, BY_KEY = new Map(ITEMS.map((i) => [i.key, i]));
  const SECTIONS = new Map(IT.sections.map((s) => [s.id, s.title]));
  const plain = (h) => { const d = el("div", { html: h }); return d.textContent; };
  function itemsList(active) {
    const list = $("it-list"), q = $("it-search").value.toLowerCase(), onlyOnline = $("it-online").checked;
    list.replaceChildren();
    for (const [sid, title] of SECTIONS) {
      const its = ITEMS.filter((i) => i.section === sid && (!onlyOnline || i.sid) &&
        (!q || (i.number + " " + plain(i.caption)).toLowerCase().includes(q)));
      if (!its.length) continue;
      list.append(el("div", { class: "sec-title" }, title));
      its.forEach((i) => {
        const a = el("a", { class: "it-link" + (i.key === active ? " active" : ""), href: "#" + i.key });
        const cap = plain(i.caption);
        a.append(el("span", { class: "it-num" }, i.number), el("span", {}, cap.length > 95 ? cap.slice(0, 92) + "…" : cap));
        list.append(a);
      });
    }
  }
  function renderItem(it) {
    const pane = $("it-content");
    pane.replaceChildren();
    const card = el("article", { class: "card", id: "card-" + it.key });
    const b = el("div", { class: "badges" });
    b.append(el("span", { class: "badge" }, it.number || it.name));
    b.append(el("span", { class: "badge" + (it.sid ? " online" : "") },
      it.sid ? "Online only: cited in the paper as " + it.number : (it.section === "paper" ? "Figure of the main text" : "Also printed in the paper's appendix")));
    b.append(el("span", { class: "badge" }, SECTIONS.get(it.section) || ""));
    card.append(b, el("p", { class: "caption", html: it.caption }));
    if (it.kind === "figure" && it.image) {
      card.append(el("img", { class: "item-img", src: it.image, alt: plain(it.caption), loading: "lazy" }));
    } else if (it.kind === "table") {
      const box = el("div"); card.append(box);
      renderTable(box, it.columns, it.rows, { csv: it.csv });
    } else if (it.kind === "codebook") {
      const t = CB.tables[it.name], box = el("div"); card.append(box);
      renderTable(box, t.columns, t.rows, { wrap: new Set([1]) });
    }
    if (it.notes && it.notes.length) {
      const d = el("details", { class: "notes", open: "" });
      d.append(el("summary", {}, "How it was computed and how to read it"));
      it.notes.forEach((n) => {
        if (typeof n === "string") d.append(el("p", { html: n }));
        else { d.append(el("h4", {}, n.heading)); const ul = el("ul"); n.items.forEach((x) => ul.append(el("li", { html: x }))); d.append(ul); }
      });
      card.append(d);
    }
    pane.append(card);
    window.scrollTo({ top: 0 });
  }

  // ------------------------------------------------------------ codebook
  function codebook() {
    const box = $("cb-content");
    if (box.childElementCount) return;
    const intro = el("div", { class: "card prose" });
    intro.append(el("h2", {}, "Rationale codebook"), el("p", {}, CB.unit_of_analysis));
    intro.append(el("h3", {}, "General rules"));
    const ul = el("ul"); CB.general_rules.forEach((r) => ul.append(el("li", {}, r))); intro.append(ul);
    intro.append(el("p", { class: "hint" }, "Results use categories whose two LLM judges agree with Cohen's κ ≥ 0.7; " +
      "0.5–0.7 is exploratory; below 0.5 a category is not analysed (agreement per category: see the reliability table)."));
    box.append(intro);
    ITEMS.filter((i) => i.kind === "codebook").forEach((it) => {
      const c = el("div", { class: "card", id: "cb-" + it.key });
      c.append(el("h2", {}, `${it.number}. ${plain(it.caption)}`));
      const t = CB.tables[it.name], tb = el("div"); c.append(tb);
      renderTable(tb, t.columns, t.rows, { wrap: new Set([1]), filter: false });
      box.append(c);
    });
  }

  // ------------------------------------------------------------ routing
  const VIEWS = ["overview", "explorer", "items", "codebook", "about"];
  function show(view) {
    VIEWS.forEach((v) => { $("view-" + v).hidden = v !== view; });
    document.querySelectorAll("nav a").forEach((a) => a.classList.toggle("active", a.dataset.view === view));
  }
  function route() {
    const h = decodeURIComponent(location.hash.slice(1)) || "overview";
    const [view, arg] = h.split("/");
    if (BY_KEY.has(h)) { show("items"); itemsList(h); renderItem(BY_KEY.get(h)); return; }
    if (view === "items") { show("items"); const first = ITEMS.find((i) => i.section !== "paper") || ITEMS[0];
      itemsList(first.key); renderItem(first); return; }
    if (view === "explorer") { show("explorer"); explorer(arg); return; }
    if (view === "codebook") { show("codebook"); codebook(); return; }
    if (view === "about") { show("about"); return; }
    show("overview"); overview();
  }

  // ------------------------------------------------------------ init
  CONFIGS.forEach(([lab], i) => { $("ov-config").append(el("option", { value: i }, lab)); $("ex-config").append(el("option", { value: i }, lab)); });
  $("ov-config").value = "4"; $("ex-config").value = "5";
  $("ov-config").addEventListener("change", overview);
  $("it-search").addEventListener("input", () => itemsList(location.hash.slice(1)));
  $("it-online").addEventListener("change", () => itemsList(location.hash.slice(1)));
  $("ab-generated").textContent = `Data generated ${IT.generated}. ${EX.note}`;
  explorerInit();
  window.addEventListener("hashchange", route);
  route();
})();
